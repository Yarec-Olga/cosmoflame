def get_choice(count):
    """
    :param count: how many options do you have
    :return: answer for question
    """
    answer = int(input("Сделай свой выбор: "))
    while answer not in [i for i in range(1, count + 1)]:
        answer = input("Это не верный выбор! Попробуй ещё раз: ")
    return answer

